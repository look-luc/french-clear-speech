DROP TABLE IF EXISTS PUBLIC.DATA_RESPONSE_AUDIO;

DROP TABLE IF EXISTS PUBLIC.DATA_RESPONSE;

DROP TABLE IF EXISTS PUBLIC.AUDIO;

CREATE TABLE PUBLIC.AUDIO (
	PRIMARY_KEY SERIAL NOT NULL,
	AUDIO_STR CHARACTER VARYING(128) NOT NULL,
	CONSTRAINT PK_AUDIO PRIMARY KEY (PRIMARY_KEY)
);

ALTER TABLE IF EXISTS PUBLIC.AUDIO OWNER TO LUCDENARDI;

CREATE TABLE PUBLIC.DATA_RESPONSE (
	PRIMARY_KEY SERIAL NOT NULL,
	SUBJECT CHARACTER VARYING(100) NOT NULL,
	AGE SMALLINT NOT NULL,
	GENDER CHARACTER VARYING(32) NOT NULL,
	TRIAL_INDEX CHARACTER VARYING(30),
	RESPONSE TEXT NOT NULL,
	CONFIDENCE SMALLINT NOT NULL,
	CUSTOM_TAG CHARACTER VARYING(100) DEFAULT 'clear_speech',
	CONSTRAINT PK_DATA_RESPONSE PRIMARY KEY (PRIMARY_KEY)
);

ALTER TABLE IF EXISTS PUBLIC.DATA_RESPONSE OWNER TO LUCDENARDI;

CREATE TABLE PUBLIC.DATA_RESPONSE_AUDIO (
	DATA_RESPONSE_ID INT NOT NULL,
	AUDIO_ID INT NOT NULL,
	CONSTRAINT PK_DATA_RESPONSE_AUDIO PRIMARY KEY (DATA_RESPONSE_ID, AUDIO_ID),
	CONSTRAINT FK_RESPONSE FOREIGN KEY (DATA_RESPONSE_ID) REFERENCES PUBLIC.DATA_RESPONSE (PRIMARY_KEY) ON DELETE CASCADE,
	CONSTRAINT FK_AUDIO FOREIGN KEY (AUDIO_ID) REFERENCES PUBLIC.AUDIO (PRIMARY_KEY) ON DELETE CASCADE
);

ALTER TABLE IF EXISTS PUBLIC.DATA_RESPONSE_AUDIO OWNER TO LUCDENARDI;

CREATE INDEX IF NOT EXISTS FKI_RESPONSE_AUDIO ON PUBLIC.DATA_RESPONSE_AUDIO (DATA_RESPONSE_ID, AUDIO_ID);