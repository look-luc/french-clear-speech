SELECT 
    dr.PRIMARY_KEY AS response_id,
    dr.SUBJECT,
    dr.AGE,
    dr.GENDER,
    dr.TRIAL_INDEX,
    dr.RESPONSE,
    dr.CONFIDENCE,
    dr.CUSTOM_TAG,
    a.PRIMARY_KEY AS audio_id,
    a.AUDIO_STR
FROM PUBLIC.DATA_RESPONSE_AUDIO dra
INNER JOIN PUBLIC.DATA_RESPONSE dr ON dra.DATA_RESPONSE_ID = dr.PRIMARY_KEY
INNER JOIN PUBLIC.AUDIO a ON dra.AUDIO_ID = a.PRIMARY_KEY;